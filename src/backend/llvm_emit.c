#include "../../include/backend.h"

static void llvm_ld(FILE *out, IROperand op, const char *reg, int *ssa) {
    if (op.kind == OPERAND_CONST) fprintf(out, "  %%%s = add i32 0, %d\n", reg, op.val);
    else if (op.kind == OPERAND_TEMP) { int r = (*ssa)++; fprintf(out, "  %%ld%d = load i32, ptr %%t%d, align 4\n  %%%s = add i32 0, %%ld%d\n", r, op.val, reg, r); }
    else if (op.kind == OPERAND_VAR) { int r = (*ssa)++; fprintf(out, "  %%ld%d = load i32, ptr %%v%d, align 4\n  %%%s = add i32 0, %%ld%d\n", r, op.val, reg, r); }
}

static void llvm_st(FILE *out, IROperand dst, const char *reg) {
    if (dst.kind == OPERAND_TEMP) fprintf(out, "  store i32 %%%s, ptr %%t%d, align 4\n", reg, dst.val);
    else if (dst.kind == OPERAND_VAR) fprintf(out, "  store i32 %%%s, ptr %%v%d, align 4\n", reg, dst.val);
}

void emit_llvm_ir(const IRProgram *irp, FILE *out) {
    fprintf(out, "; Generated by cminorcc %s\ntarget triple = \"x86_64-pc-linux-gnu\"\n\n", CMINOR_VERSION);
    for (size_t i = 0; i < irp->func_count; i++) {
        const IRFunction *fn = &irp->funcs[i];
        fprintf(out, "define %s @%s(", fn->ret_type == TYPE_INT ? "i32" : "void", fn->name);
        for (size_t p = 0; p < fn->param_count; p++) fprintf(out, "%si32 %%arg%zu", p ? ", " : "", p);
        fprintf(out, ") {\nentry:\n");
        for (size_t v = 0; v < fn->var_count; v++) fprintf(out, "  %%v%d = alloca i32, align 4\n  store i32 0, ptr %%v%d, align 4\n", fn->vars[v].sym_id, fn->vars[v].sym_id);
        for (int t = 0; t < fn->next_temp; t++) fprintf(out, "  %%t%d = alloca i32, align 4\n  store i32 0, ptr %%t%d, align 4\n", t, t);
        for (size_t p = 0; p < fn->param_count; p++) fprintf(out, "  store i32 %%arg%zu, ptr %%v%d, align 4\n", p, fn->param_sym_ids[p]);

        int ssa = 0, pargs[MAX_PARAMS]; size_t pcnt = 0;
        for (size_t c = 0; c < fn->code_count; c++) {
            const IRInstr *ins = &fn->code[c];
            switch (ins->op) {
                case IR_LABEL: fprintf(out, "  br label %%L%d\nL%d:\n", ins->label_id, ins->label_id); break;
                case IR_MOV: { char r1[32]; snprintf(r1,32,"r%d",ssa++); llvm_ld(out,ins->src1,r1,&ssa); llvm_st(out,ins->dst,r1); break; }
                case IR_ADD: case IR_SUB: case IR_MUL: case IR_DIV: case IR_MOD: {
                    char r1[32], r2[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(r2,32,"r%d",ssa++); snprintf(res,32,"r%d",ssa++);
                    llvm_ld(out,ins->src1,r1,&ssa); llvm_ld(out,ins->src2,r2,&ssa);
                    const char *op = ins->op==IR_ADD?"add":(ins->op==IR_SUB?"sub":(ins->op==IR_MUL?"mul":(ins->op==IR_DIV?"sdiv":"srem")));
                    fprintf(out, "  %%%s = %s i32 %%%s, %%%s\n", res, op, r1, r2); llvm_st(out,ins->dst,res); break;
                }
                case IR_NEG: { char r1[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(res,32,"r%d",ssa++); llvm_ld(out,ins->src1,r1,&ssa); fprintf(out,"  %%%s = sub i32 0, %%%s\n",res,r1); llvm_st(out,ins->dst,res); break; }
                case IR_NOT: { char r1[32], cmp[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(cmp,32,"c%d",ssa++); snprintf(res,32,"r%d",ssa++); llvm_ld(out,ins->src1,r1,&ssa); fprintf(out,"  %%%s = icmp eq i32 %%%s, 0\n  %%%s = zext i1 %%%s to i32\n",cmp,r1,res,cmp); llvm_st(out,ins->dst,res); break; }
                case IR_LT: case IR_LE: case IR_GT: case IR_GE: case IR_EQ: case IR_NE: {
                    char r1[32], r2[32], cmp[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(r2,32,"r%d",ssa++); snprintf(cmp,32,"c%d",ssa++); snprintf(res,32,"r%d",ssa++);
                    llvm_ld(out,ins->src1,r1,&ssa); llvm_ld(out,ins->src2,r2,&ssa);
                    const char *pr = ins->op==IR_LT?"slt":(ins->op==IR_LE?"sle":(ins->op==IR_GT?"sgt":(ins->op==IR_GE?"sge":(ins->op==IR_EQ?"eq":"ne"))));
                    fprintf(out, "  %%%s = icmp %s i32 %%%s, %%%s\n  %%%s = zext i1 %%%s to i32\n", cmp, pr, r1, r2, res, cmp); llvm_st(out,ins->dst,res); break;
                }
                case IR_JMP: { int d = ssa++; fprintf(out, "  br label %%L%d\ndead_%d:\n", ins->label_id, d); break; }
                case IR_JZ: { char r1[32], cmp[32]; int f = ssa++; snprintf(r1,32,"r%d",ssa++); snprintf(cmp,32,"c%d",ssa++); llvm_ld(out,ins->src1,r1,&ssa); fprintf(out,"  %%%s = icmp eq i32 %%%s, 0\n  br i1 %%%s, label %%L%d, label %%fall_%d\nfall_%d:\n",cmp,r1,cmp,ins->label_id,f,f); break; }
                case IR_JNZ: { char r1[32], cmp[32]; int f = ssa++; snprintf(r1,32,"r%d",ssa++); snprintf(cmp,32,"c%d",ssa++); llvm_ld(out,ins->src1,r1,&ssa); fprintf(out,"  %%%s = icmp ne i32 %%%s, 0\n  br i1 %%%s, label %%L%d, label %%fall_%d\nfall_%d:\n",cmp,r1,cmp,ins->label_id,f,f); break; }
                case IR_ARG: { int rid = ssa++; char r1[32]; snprintf(r1,32,"r%d",rid); llvm_ld(out,ins->src1,r1,&ssa); if (pcnt < MAX_PARAMS) pargs[pcnt++] = rid; break; }
                case IR_CALL:
                    if (ins->dst.kind != OPERAND_NONE) {
                        char res[32]; snprintf(res,32,"call%d",ssa++); fprintf(out,"  %%%s = call i32 @%s(",res,ins->callee);
                        for (size_t a=0;a<pcnt;a++) fprintf(out,"%si32 %%r%d",a?", ":"",pargs[a]);
                        fprintf(out,")\n"); llvm_st(out,ins->dst,res);
                    } else {
                        fprintf(out,"  call void @%s(",ins->callee);
                        for (size_t a=0;a<pcnt;a++) fprintf(out,"%si32 %%r%d",a?", ":"",pargs[a]);
                        fprintf(out,")\n");
                    }
                    pcnt = 0; break;
                case IR_RET: { char r1[32]; int d = ssa++; snprintf(r1,32,"r%d",ssa++); llvm_ld(out,ins->src1,r1,&ssa); fprintf(out,"  ret i32 %%%s\nafter_%d:\n",r1,d); break; }
                case IR_RET_VOID: { int d = ssa++; fprintf(out,"  ret void\nafter_%d:\n",d); break; }
            }
        }
        fprintf(out, fn->ret_type == TYPE_INT ? "  ret i32 0\n}\n\n" : "  ret void\n}\n\n");
    }
}
