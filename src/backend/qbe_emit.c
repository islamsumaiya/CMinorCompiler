#include "../../include/backend.h"

static void qbe_ld(FILE *out, IROperand op, const char *reg) {
    if (op.kind == OPERAND_CONST) fprintf(out, "  %%%s =w copy %d\n", reg, op.val);
    else if (op.kind == OPERAND_TEMP) fprintf(out, "  %%%s =w loadw %%t%d\n", reg, op.val);
    else if (op.kind == OPERAND_VAR) fprintf(out, "  %%%s =w loadw %%v%d\n", reg, op.val);
}

static void qbe_st(FILE *out, IROperand dst, const char *reg) {
    if (dst.kind == OPERAND_TEMP) fprintf(out, "  storew %%%s, %%t%d\n", reg, dst.val);
    else if (dst.kind == OPERAND_VAR) fprintf(out, "  storew %%%s, %%v%d\n", reg, dst.val);
}

void emit_qbe_il(const IRProgram *irp, FILE *out) {
    fprintf(out, "# Generated by cminorcc %s\n\n", CMINOR_VERSION);
    for (size_t i = 0; i < irp->func_count; i++) {
        const IRFunction *fn = &irp->funcs[i];
        fprintf(out, "export function %s$%s(", fn->ret_type == TYPE_INT ? "w " : "", fn->name);
        for (size_t p = 0; p < fn->param_count; p++) fprintf(out, "%sw %%arg%zu", p ? ", " : "", p);
        fprintf(out, ") {\n@start\n");
        for (size_t v = 0; v < fn->var_count; v++) fprintf(out, "  %%v%d =l alloc4 4\n  storew 0, %%v%d\n", fn->vars[v].sym_id, fn->vars[v].sym_id);
        for (int t = 0; t < fn->next_temp; t++) fprintf(out, "  %%t%d =l alloc4 4\n  storew 0, %%t%d\n", t, t);
        for (size_t p = 0; p < fn->param_count; p++) fprintf(out, "  storew %%arg%zu, %%v%d\n", p, fn->param_sym_ids[p]);

        int ssa = 0, pargs[MAX_PARAMS]; size_t pcnt = 0;
        for (size_t c = 0; c < fn->code_count; c++) {
            const IRInstr *ins = &fn->code[c];
            switch (ins->op) {
                case IR_LABEL: fprintf(out, "@L%d\n", ins->label_id); break;
                case IR_MOV: { char r1[32]; snprintf(r1,32,"r%d",ssa++); qbe_ld(out,ins->src1,r1); qbe_st(out,ins->dst,r1); break; }
                case IR_ADD: case IR_SUB: case IR_MUL: case IR_DIV: case IR_MOD: {
                    char r1[32], r2[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(r2,32,"r%d",ssa++); snprintf(res,32,"r%d",ssa++);
                    qbe_ld(out,ins->src1,r1); qbe_ld(out,ins->src2,r2);
                    const char *op = ins->op==IR_ADD?"add":(ins->op==IR_SUB?"sub":(ins->op==IR_MUL?"mul":(ins->op==IR_DIV?"div":"rem")));
                    fprintf(out, "  %%%s =w %s %%%s, %%%s\n", res, op, r1, r2); qbe_st(out,ins->dst,res); break;
                }
                case IR_NEG: { char r1[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(res,32,"r%d",ssa++); qbe_ld(out,ins->src1,r1); fprintf(out,"  %%%s =w neg %%%s\n",res,r1); qbe_st(out,ins->dst,res); break; }
                case IR_NOT: { char r1[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(res,32,"r%d",ssa++); qbe_ld(out,ins->src1,r1); fprintf(out,"  %%%s =w ceqw %%%s, 0\n",res,r1); qbe_st(out,ins->dst,res); break; }
                case IR_LT: case IR_LE: case IR_GT: case IR_GE: case IR_EQ: case IR_NE: {
                    char r1[32], r2[32], res[32]; snprintf(r1,32,"r%d",ssa++); snprintf(r2,32,"r%d",ssa++); snprintf(res,32,"r%d",ssa++);
                    qbe_ld(out,ins->src1,r1); qbe_ld(out,ins->src2,r2);
                    const char *pr = ins->op==IR_LT?"csltw":(ins->op==IR_LE?"cslew":(ins->op==IR_GT?"csgtw":(ins->op==IR_GE?"csgew":(ins->op==IR_EQ?"ceqw":"cnew"))));
                    fprintf(out, "  %%%s =w %s %%%s, %%%s\n", res, pr, r1, r2); qbe_st(out,ins->dst,res); break;
                }
                case IR_JMP: { int d = ssa++; fprintf(out, "  jmp @L%d\n@dead_%d\n", ins->label_id, d); break; }
                case IR_JZ: { char r1[32]; int f = ssa++; snprintf(r1,32,"r%d",ssa++); qbe_ld(out,ins->src1,r1); fprintf(out,"  jnz %%%s, @fall_%d, @L%d\n@fall_%d\n",r1,f,ins->label_id,f); break; }
                case IR_JNZ: { char r1[32]; int f = ssa++; snprintf(r1,32,"r%d",ssa++); qbe_ld(out,ins->src1,r1); fprintf(out,"  jnz %%%s, @L%d, @fall_%d\n@fall_%d\n",r1,ins->label_id,f,f); break; }
                case IR_ARG: { int rid = ssa++; char r1[32]; snprintf(r1,32,"r%d",rid); qbe_ld(out,ins->src1,r1); if (pcnt < MAX_PARAMS) pargs[pcnt++] = rid; break; }
                case IR_CALL:
                    if (ins->dst.kind != OPERAND_NONE) {
                        char res[32]; snprintf(res,32,"call%d",ssa++); fprintf(out,"  %%%s =w call $%s(",res,ins->callee);
                        for (size_t a=0;a<pcnt;a++) fprintf(out,"%sw %%r%d",a?", ":"",pargs[a]);
                        fprintf(out,")\n"); qbe_st(out,ins->dst,res);
                    } else {
                        fprintf(out,"  call $%s(",ins->callee);
                        for (size_t a=0;a<pcnt;a++) fprintf(out,"%sw %%r%d",a?", ":"",pargs[a]);
                        fprintf(out,")\n");
                    }
                    pcnt = 0; break;
                case IR_RET: { char r1[32]; int d = ssa++; snprintf(r1,32,"r%d",ssa++); qbe_ld(out,ins->src1,r1); fprintf(out,"  ret %%%s\n@after_%d\n",r1,d); break; }
                case IR_RET_VOID: { int d = ssa++; fprintf(out,"  ret\n@after_%d\n",d); break; }
            }
        }
        fprintf(out, fn->ret_type == TYPE_INT ? "  ret 0\n}\n\n" : "  ret\n}\n\n");
    }
}
